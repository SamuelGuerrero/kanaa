import "@styles/globals.css";

import { type Metadata } from "next";
import { Roboto_Serif } from "next/font/google";
import localFont from "next/font/local";
import { cookies, headers } from "next/headers";

import { Footer, Navbar } from "@/components/organisms";
import { LanguageProvider } from "@/i18n";

import type { ReactNode } from "react";

export const metadata: Metadata = {
  title: "Kanaa",
  description: "Generated by create-t3-app",
  icons: [{ rel: "icon", url: "/favicon.ico" }],
};

const robotoSerif = Roboto_Serif({
  subsets: ["latin"],
  variable: "--font-roboto",
  display: "swap",
});

const gilroy = localFont({
  src: [
    {
      path: "../../public/fonts/Gilroy-Light.ttf",
      weight: "300",
      style: "normal",
    },
    {
      path: "../../public/fonts/Gilroy-Regular.ttf",
      weight: "400",
      style: "normal",
    },
    {
      path: "../../public/fonts/Gilroy-Medium.ttf",
      weight: "500",
      style: "normal",
    },
    {
      path: "../../public/fonts/Gilroy-Bold.ttf",
      weight: "700",
      style: "normal",
    },
    {
      path: "../../public/fonts/Gilroy-Heavy.ttf",
      weight: "800",
      style: "normal",
    },
  ],
  variable: "--font-gilroy",
  display: "swap",
});

export default async function RootLayout({
  children,
}: Readonly<{ children: ReactNode }>) {
  const cookieStore = await cookies();
  const headerStore = await headers();
  const host = headerStore.get("x-forwarded-host") ?? headerStore.get("host");
  const localeFromHost = host?.toLowerCase().startsWith("en.") ? "en" : null;
  const localeCookie = cookieStore.get("kanaa_locale")?.value;
  const initialLocale = localeFromHost ?? (localeCookie === "en" ? "en" : "es");

  return (
    <html
      lang={initialLocale}
      className={`${robotoSerif.variable} ${gilroy.variable}`}
    >
      <head>
        <link
          rel="stylesheet"
          href="https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.1/css/all.min.css"
        />
      </head>
      <body className="bg-[url('/svg/main.svg')] bg-contain bg-top bg-repeat p-1.5 sm:p-4">
        <LanguageProvider initialLocale={initialLocale}>
          <Navbar />
          {children}
          <Footer />
        </LanguageProvider>
      </body>
    </html>
  );
}
