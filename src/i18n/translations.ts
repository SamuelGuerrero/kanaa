const normalize = (value: string) => value.replace(/\s+/g, " ").trim();

export const translateText = (value: string, locale: "es" | "en"): string => {
  if (locale === "es") return value;
  const normalizedValue = normalize(value);

  if (normalizedValue.startsWith("©") && normalizedValue.includes("Kanaa")) {
    const yearMatch = /\b(20\d{2}|19\d{2})\b/.exec(normalizedValue);
    const year = yearMatch?.[0] ?? new Date().getFullYear().toString();
    return `© ${year} — Kanaa. All rights reserved.`;
  }

  return enTranslations[normalizedValue] ?? value;
};
